export function statePortal(state: StateCode): string {
  switch (state) {
    case 'QLD':
      return 'https://www.workinqueensland.com.au';
    case 'WA':
      return 'https://www.workandstay.wa.gov.au';
    default:
      return 'https://www.harvesttrail.gov.au';
  }
}

