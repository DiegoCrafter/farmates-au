export const translations: Record<Lang, Dict> = { es, en, pt };

export function detectLang(): Lang {
  const saved = typeof window !== 'undefined' ? window.localStorage.getItem('farmates.lang') : null;
  if (saved === 'es' || saved === 'en' || saved === 'pt') return saved;
  const nav = typeof window !== 'undefined' ? (window.navigator.language || 'en').toLowerCase() : 'en';
  if (nav.startsWith('pt')) return 'pt';
  if (nav.startsWith('es')) return 'es';
  return 'en';
}
